package org.jetbrains.kotlin.tools.idl.surface

import org.jetbrains.kotlin.tools.idl.frontend.IdlSource
import org.jetbrains.kotlin.tools.idl.ir.*

/** Something the allowlisted specs reference that is deliberately not part of the surface. */
sealed interface Exclusion {
    /** Spec shortname or type name; also the key [PrunedItem.excludedBy] refers to. */
    val key: String
    val reason: String

    /** A whole webref spec. */
    data class Spec(override val key: String, override val reason: String) : Exclusion

    /** A single type that no spec in the corpus defines (an ECMAScript built-in without a hand-written declaration). */
    data class Type(override val key: String, override val reason: String) : Exclusion
}

/** Something removed from the surface because it depends on an excluded spec. */
data class PrunedItem(
    /** [Exclusion.key] of the exclusion ultimately responsible. */
    val excludedBy: String,
    /** The allowlisted spec the item was removed from. */
    val spec: String,
    /** Human-readable description, in Web IDL syntax. */
    val description: String,
)

class SurfaceResult(
    val ir: IdlIR,
    val pruned: List<PrunedItem>,
    /** Definitions dropped because a hand-written built-in provides them, as `spec: name`. */
    val replacedByBuiltins: List<String>,
    private val exclusions: List<Exclusion>,
) {
    /** The committed `surface-report.txt`: every pruning decision, grouped by the excluded spec that caused it. */
    fun report(): String = buildString {
        append("# Generated by the kotlinx-browser generator (surface pass). Do not edit.\n")
        append("# What was removed from the allowlisted specs because it depends on an excluded spec,\n")
        append("# and which definitions are provided by hand-written built-ins instead of being generated.\n")
        for (exclusion in exclusions) {
            val kind = when (exclusion) {
                is Exclusion.Spec -> "spec"
                is Exclusion.Type -> "type"
            }
            append("\n## ").append(kind).append(' ').append(exclusion.key).append(" — ").append(exclusion.reason)
                .append('\n')
            pruned.filter { it.excludedBy == exclusion.key }.forEach {
                append(it.spec).append(": ").append(it.description).append('\n')
            }
        }
        append("\n## built-ins (hand-written, not generated)\n")
        replacedByBuiltins.forEach { append(it).append('\n') }
    }
}

class SurfaceException(val problems: List<String>) : RuntimeException(
    "Surface resolution failed with ${problems.size} problem(s):\n" + problems.joinToString("\n") { "  - $it" }
)

/**
 * Builds the generated surface from the whole corpus:
 *  1. takes the allowlisted specs;
 *  2. drops definitions that hand-written built-ins provide ([Builtins]);
 *  3. resolves every type reference, inheritance, `includes` and partial against the allowlisted specs and built-ins;
 *  4. prunes whatever depends on an excluded spec — union alternatives are dropped, members and definitions that
 *     cannot be expressed without the excluded type are removed — repeating until nothing more depends on removed
 *     definitions.
 *
 * It fails (with every problem listed) if a reference resolves to neither an allowlisted spec, a built-in nor an
 * excluded spec, or if an exclusion no longer prunes anything.
 */
object SurfaceBuilder {

    fun build(corpus: IdlIR, included: List<IdlSource>, exclusions: List<Exclusion>): SurfaceResult {
        val problems = mutableListOf<String>()
        val corpusSpecs = corpus.specs.associateBy { it.name }
        val includedNames = included.map { it.spec }.toSet()
        val excludedSpecs = exclusions.filterIsInstance<Exclusion.Spec>().map { it.key }.toSet()
        val excludedTypes = exclusions.filterIsInstance<Exclusion.Type>().map { it.key }.toSet()

        for (source in included) {
            if (source.spec !in corpusSpecs) {
                problems += "allowlisted spec '${source.spec}' is not in the corpus"
            }
        }
        for (spec in excludedSpecs) {
            if (spec !in corpusSpecs) problems += "excluded spec '$spec' is not in the corpus"
            if (spec in includedNames) problems += "spec '$spec' is both allowlisted and excluded"
        }
        if (problems.isNotEmpty()) throw SurfaceException(problems)

        val definedIn = mutableMapOf<String, MutableSet<String>>()
        for (spec in corpus.specs) for (definition in spec.definitions) {
            definition.definedNames().forEach { definedIn.getOrPut(it) { linkedSetOf() } += spec.name }
        }
        for (type in excludedTypes) {
            if (type in definedIn) problems += "excluded type '$type' is defined in ${
                definedIn.getValue(type).joinToString()
            }; exclude the spec instead"
            if (Builtins.isBuiltin(type)) problems += "excluded type '$type' is a built-in"
        }
        if (problems.isNotEmpty()) throw SurfaceException(problems)

        val replacedByBuiltins = mutableListOf<String>()
        var specs = included.map { source ->
            val definitions = corpusSpecs.getValue(source.spec).definitions.filter { definition ->
                val builtin = definition is IdlNamedDefinition && Builtins.isBuiltin(definition.name)
                if (builtin) replacedByBuiltins += "${source.spec}: ${definition.name}"
                !builtin
            }
            IdlSpec(source.spec, source.packageName, definitions)
        }

        val pruner = Pruner(definedIn, excludedSpecs, excludedTypes)
        do {
            pruner.startPass(specs)
            specs = specs.map { spec ->
                spec.copy(definitions = spec.definitions.mapNotNull {
                    pruner.prune(
                        it,
                        spec.name
                    )
                })
            }
        } while (pruner.removedDefinitionInLastPass)

        problems += pruner.unresolvedProblems()
        val used = pruner.pruned.map { it.excludedBy }.toSet()
        for (exclusion in exclusions) {
            if (exclusion.key !in used) problems += when (exclusion) {
                is Exclusion.Spec -> "excluded spec '${exclusion.key}' prunes nothing any more; remove it from EXCLUDED_SPECS"
                is Exclusion.Type -> "excluded type '${exclusion.key}' prunes nothing any more; remove it from EXCLUDED_TYPES"
            }
        }
        if (problems.isNotEmpty()) throw SurfaceException(problems)

        return SurfaceResult(IdlIR(specs), pruner.pruned, replacedByBuiltins, exclusions)
    }
}

/** Names a definition makes available to references: its own name (if not partial) and its `[LegacyWindowAlias]`es. */
internal fun IdlDefinition.definedNames(): List<String> {
    val own = when (this) {
        is IdlPartialable -> if (partial) null else name
        is IdlNamedDefinition -> name
        is IdlIncludes -> null
    }
    return listOfNotNull(own) + legacyWindowAliases()
}

fun IdlDefinition.legacyWindowAliases(): List<String> {
    if (this !is IdlInterface || partial) return emptyList()
    return when (val rhs = extAttrs.find("LegacyWindowAlias")?.rhs) {
        is IdlExtendedAttributeValue.Identifier -> listOf(rhs.value)
        is IdlExtendedAttributeValue.IdentifierList -> rhs.values
        else -> emptyList()
    }
}

private class Pruner(
    private val definedIn: Map<String, Set<String>>,
    private val excludedSpecs: Set<String>,
    private val excludedTypes: Set<String>,
) {
    val pruned = mutableListOf<PrunedItem>()

    /** Definitions removed in an earlier pass → the excluded spec responsible. */
    private val removedDefinitions = mutableMapOf<String, String>()
    private var available: Set<String> = emptySet()
    private val unresolved = linkedMapOf<String, MutableSet<String>>()
    var removedDefinitionInLastPass = false
        private set

    fun startPass(specs: List<IdlSpec>) {
        available = specs.flatMap { spec -> spec.definitions.flatMap { it.definedNames() } }.toSet()
        unresolved.clear()
        removedDefinitionInLastPass = false
    }

    fun unresolvedProblems(): List<String> = unresolved.map { (name, from) ->
        val where = definedIn[name]
        val cause = if (where == null) "is not defined anywhere in the corpus"
        else "is defined in ${where.joinToString()}, which is neither allowlisted nor excluded"
        "'$name' (referenced from ${from.take(3).joinToString()}${if (from.size > 3) ", …" else ""}) $cause"
    }

    // ---- resolution -------------------------------------------------------------------------------------------------

    /** `null` when [name] resolves; otherwise the key of the exclusion it depends on. Unresolvable names are recorded. */
    private fun exclusionOf(name: String, from: String): String? {
        if (name in available || Builtins.isBuiltin(name)) return null
        removedDefinitions[name]?.let { return it }
        if (name in excludedTypes) return name
        val where = definedIn[name].orEmpty()
        where.firstOrNull { it in excludedSpecs }?.let { return it }
        unresolved.getOrPut(name) { linkedSetOf() } += from
        return null
    }

    private sealed interface TypeResult {
        /** [type] with excluded union alternatives removed; [removed] lists `(alternative, excluded spec)`. */
        data class Kept(val type: IdlType, val removed: List<Pair<String, String>>) : TypeResult

        /** The type cannot be expressed: [name] depends on [excludedBy]. */
        data class Dropped(val name: String, val excludedBy: String) : TypeResult
    }

    private fun pruneType(type: IdlType, from: String): TypeResult = when (type) {
        is IdlNamedType -> exclusionOf(type.name, from)
            ?.let { TypeResult.Dropped(type.name, it) }
            ?: TypeResult.Kept(type, emptyList())

        is IdlGenericType -> {
            val results = type.arguments.map { pruneType(it, from) }
            results.filterIsInstance<TypeResult.Dropped>().firstOrNull()
                ?: results.filterIsInstance<TypeResult.Kept>().let { kept ->
                    TypeResult.Kept(type.copy(arguments = kept.map { it.type }), kept.flatMap { it.removed })
                }
        }

        is IdlUnionType -> {
            val results = type.members.map { pruneType(it, from) }
            val kept = results.filterIsInstance<TypeResult.Kept>()
            val dropped = results.filterIsInstance<TypeResult.Dropped>()
            val removed = dropped.map { it.name to it.excludedBy } + kept.flatMap { it.removed }
            when {
                kept.isEmpty() -> dropped.first()
                kept.size == 1 -> {
                    val single = kept.single().type
                    TypeResult.Kept(
                        single.with(single.nullable || type.nullable, type.extAttrs + single.extAttrs),
                        removed
                    )
                }

                else -> TypeResult.Kept(type.copy(members = kept.map { it.type }), removed)
            }
        }
    }

    private fun IdlType.with(nullable: Boolean, extAttrs: List<IdlExtendedAttribute>): IdlType = when (this) {
        is IdlNamedType -> copy(nullable = nullable, extAttrs = extAttrs)
        is IdlGenericType -> copy(nullable = nullable, extAttrs = extAttrs)
        is IdlUnionType -> copy(nullable = nullable, extAttrs = extAttrs)
    }

    // ---- definitions ------------------------------------------------------------------------------------------------

    fun prune(definition: IdlDefinition, spec: String): IdlDefinition? {
        val label = definition.label()

        fun removeDefinition(name: String, excludedBy: String): IdlDefinition? {
            pruned += PrunedItem(excludedBy, spec, "removed ${label}: depends on $name")
            if (definition is IdlNamedDefinition && !(definition is IdlPartialable && definition.partial)) {
                removedDefinitions[definition.name] = excludedBy
                definition.legacyWindowAliases().forEach { removedDefinitions[it] = excludedBy }
                removedDefinitionInLastPass = true
            }
            return null
        }

        // A partial (or an includes statement) whose main definition depends on an excluded spec goes with it.
        val anchor = when (definition) {
            is IdlPartialable -> if (definition.partial) definition.name else null
            is IdlIncludes -> definition.target
            else -> null
        }
        anchor?.let { name -> exclusionOf(name, "$spec: $label")?.let { return removeDefinition(name, it) } }

        return when (definition) {
            is IdlInterface -> {
                definition.inheritance?.let { parent ->
                    exclusionOf(
                        parent,
                        "$spec: $label"
                    )?.let { return removeDefinition(parent, it) }
                }
                definition.copy(
                    members = pruneMembers(definition.members, spec, label),
                    extAttrs = pruneExtAttrs(definition.extAttrs, spec, label),
                )
            }

            is IdlNamespace -> definition.copy(members = pruneMembers(definition.members, spec, label))
            is IdlDictionary -> {
                definition.inheritance?.let { parent ->
                    exclusionOf(
                        parent,
                        "$spec: $label"
                    )?.let { return removeDefinition(parent, it) }
                }
                definition.copy(members = definition.members.mapNotNull { field ->
                    when (val r = pruneType(field.type, "$spec: $label")) {
                        is TypeResult.Dropped -> null.also {
                            pruned += PrunedItem(
                                r.excludedBy,
                                spec,
                                "removed from $label: ${field.render()}"
                            )
                        }

                        is TypeResult.Kept -> field.copy(type = r.type)
                            .also { reportNarrowed(r, spec, label, field.render()) }
                    }
                })
            }

            is IdlCallback -> {
                val types = listOf(definition.returnType) + definition.arguments.map { it.type }
                val results = types.map { pruneType(it, "$spec: $label") }
                results.filterIsInstance<TypeResult.Dropped>().firstOrNull()
                    ?.let { return removeDefinition(it.name, it.excludedBy) }
                results.forEach { reportNarrowed(it as TypeResult.Kept, spec, label, definition.render()) }
                definition.copy(
                    returnType = (results[0] as TypeResult.Kept).type,
                    arguments = definition.arguments.mapIndexed { i, a -> a.copy(type = (results[i + 1] as TypeResult.Kept).type) },
                )
            }

            is IdlTypedef -> when (val r = pruneType(definition.type, "$spec: $label")) {
                is TypeResult.Dropped -> removeDefinition(r.name, r.excludedBy)
                is TypeResult.Kept -> definition.copy(type = r.type)
                    .also { reportNarrowed(r, spec, label, definition.render()) }
            }

            is IdlIncludes -> {
                exclusionOf(definition.mixin, "$spec: $label")?.let { return removeDefinition(definition.mixin, it) }
                definition
            }

            is IdlEnum -> definition
        }
    }

    private fun pruneMembers(members: List<IdlMember>, spec: String, owner: String): List<IdlMember> =
        members.mapNotNull { member ->
            val from = "$spec: $owner"
            val types = when (member) {
                is IdlAttribute -> listOf(member.type)
                is IdlConstant -> listOf(member.type)
                is IdlOperation -> listOfNotNull(member.returnType) + member.arguments.map { it.type }
                is IdlConstructor -> member.arguments.map { it.type }
                is IdlDeclarationMember -> member.typeArguments + member.arguments.map { it.type }
            }
            val results = types.map { pruneType(it, from) }
            val dropped = results.filterIsInstance<TypeResult.Dropped>().firstOrNull()
            if (dropped != null) {
                pruned += PrunedItem(dropped.excludedBy, spec, "removed from $owner: ${member.render()}")
                return@mapNotNull null
            }
            val kept = results.map { it as TypeResult.Kept }
            kept.forEach { reportNarrowed(it, spec, owner, member.render()) }
            member.withTypes(kept.map { it.type })
        }

    private fun IdlMember.withTypes(types: List<IdlType>): IdlMember = when (this) {
        is IdlAttribute -> copy(type = types.single())
        is IdlConstant -> copy(type = types.single())
        is IdlOperation -> {
            val offset = if (returnType != null) 1 else 0
            copy(
                returnType = if (returnType != null) types[0] else null,
                arguments = arguments.mapIndexed { i, a -> a.copy(type = types[i + offset]) },
            )
        }

        is IdlConstructor -> copy(arguments = arguments.mapIndexed { i, a -> a.copy(type = types[i]) })
        is IdlDeclarationMember -> copy(
            typeArguments = types.take(typeArguments.size),
            arguments = arguments.mapIndexed { i, a -> a.copy(type = types[typeArguments.size + i]) },
        )
    }

    /** `[LegacyFactoryFunction=X(args)]` carries argument types; drop the attribute if one depends on an excluded spec. */
    private fun pruneExtAttrs(extAttrs: List<IdlExtendedAttribute>, spec: String, owner: String) =
        extAttrs.mapNotNull { attr ->
            if (attr.arguments.isEmpty()) return@mapNotNull attr
            val results = attr.arguments.map { pruneType(it.type, "$spec: $owner") }
            results.filterIsInstance<TypeResult.Dropped>().firstOrNull()?.let {
                pruned += PrunedItem(it.excludedBy, spec, "removed from $owner: [${attr.render()}]")
                return@mapNotNull null
            }
            results.forEach { reportNarrowed(it as TypeResult.Kept, spec, owner, "[${attr.render()}]") }
            attr.copy(arguments = attr.arguments.mapIndexed { i, a -> a.copy(type = (results[i] as TypeResult.Kept).type) })
        }

    private fun reportNarrowed(result: TypeResult, spec: String, owner: String, original: String) {
        if (result !is TypeResult.Kept) return
        for ((alternative, excludedBy) in result.removed) {
            pruned += PrunedItem(excludedBy, spec, "dropped union alternative $alternative in $owner: $original")
        }
    }

    private fun IdlDefinition.label(): String = when (this) {
        is IdlInterface -> (if (partial) "partial " else "") + when (kind) {
            IdlInterfaceKind.INTERFACE -> "interface "
            IdlInterfaceKind.MIXIN -> "interface mixin "
            IdlInterfaceKind.CALLBACK_INTERFACE -> "callback interface "
        } + name

        is IdlNamespace -> (if (partial) "partial " else "") + "namespace " + name
        is IdlDictionary -> (if (partial) "partial " else "") + "dictionary " + name
        is IdlCallback -> "callback $name"
        is IdlEnum -> "enum $name"
        is IdlTypedef -> "typedef $name"
        is IdlIncludes -> "$target includes $mixin"
    }
}
